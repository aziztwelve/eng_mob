/* ───────────────────────────────────────────────────────────────────── *
 *  Helpers
 * ───────────────────────────────────────────────────────────────────── */

export function projectionCopyForGoal(goal: string | null | undefined): ProjectionCopy {
  return PROJECTION_TEMPLATES[(goal as GoalKey) ?? 'default'] ?? PROJECTION_TEMPLATES.default;
}
export function planCopyForGoal(goal: string | null | undefined): PlanCopy {
  return PLAN_TEMPLATES[(goal as GoalKey) ?? 'default'] ?? PLAN_TEMPLATES.default;
}
export function roadmapCopyForGoal(goal: string | null | undefined): RoadmapCopy {
  return ROADMAP_TEMPLATES[(goal as GoalKey) ?? 'default'] ?? ROADMAP_TEMPLATES.default;
}
