// Keep the first screen's SVGs in the JS bundle: no asset-server round trips.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const screens = ['src/components/home/home-map.tsx', 'src/components/home/home-tab-bar.tsx', 'src/components/brand-splash.tsx'];
const names = new Set();
for (const screen of screens) {
  const source = fs.readFileSync(path.join(root, screen), 'utf8');
  for (const match of source.matchAll(/require\(['"](?:\.\.\/)+assets\/figma\/home-map\/([^'"]+\.svg)['"]\)/g)) names.add(match[1]);
}
const entries = [...names].sort().map(name => {
  const xml = fs.readFileSync(path.join(root, 'assets/figma/home-map', name), 'utf8');
  return `  [require('../../assets/figma/home-map/${name}')]: ${JSON.stringify(xml)},`;
});
fs.writeFileSync(path.join(root, 'src/lib/startup-svg.generated.ts'), '// Generated by scripts/generate-startup-svg.cjs; regenerate after editing startup SVGs.\nexport const startupSvg: Record<number, string> = {\n' + entries.join('\n') + '\n};\n');
console.log(`Bundled ${entries.length} startup SVGs`);
